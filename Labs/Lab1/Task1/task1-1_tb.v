`timescale 1ns/1ps

module ALU_tb();

    reg             [31:0]  src0;
    reg             [31:0]  src1;
    reg             [3 :0]  op;
    wire            [31:0]  res;
    
    initial begin
        op = 4'd0; src0 = 32'h0000_1234; src1 = 32'h0000_5678; // 测试加法 ADD：普通加法
        #10;
                   src0 = 32'h7fff_ffff; src1 = 32'h7fff_ffff; // 两个最大正数相加（溢出边界）
        #10;
                   src0 = 32'hffff_ffff; src1 = 32'hffff_ffff; // 两个 -1 相加
        #10;
                   src0 = 32'h1234_5678; src1 = 32'h0000_0000; // 加 0（边界）
        #10;
        op = 4'd1; src0 = 32'h0000_5678; src1 = 32'h0000_1234; // 测试减法 SUB：普通减法
        #10;
                   src0 = 32'h0000_0000; src1 = 32'h0000_0001; // 0 - 1 = -1
        #10;
                   src0 = 32'h1234_5678; src1 = 32'h1234_5678; // 相同数相减
        #10;
                   src0 = 32'h8000_0000; src1 = 32'h0000_0001; // 最小负数 - 1（溢出边界）
        #10;
        op = 4'd2; src0 = 32'hffff_ffff; src1 = 32'h0000_0001; // 测试有符号小于 SLT：-1 < 1
        #10;
                   src0 = 32'h0000_0001; src1 = 32'h0000_0000; // 1 < 0
        #10;
                   src0 = 32'hffff_ffff; src1 = 32'hffff_fffe; // -1 < -2
        #10;
                   src0 = 32'h8000_0000; src1 = 32'h7fff_ffff; // 最小负数 < 最大正数（边界）
        #10;
                   src0 = 32'h1234_5678; src1 = 32'h1234_5678; // 相等情况
        #10;
        op = 4'd3; src0 = 32'hffff_ffff; src1 = 32'h0000_0001; // 测试无符号小于 SLTU：0xFFFFFFFF < 1
        #10;
                   src0 = 32'h0000_0001; src1 = 32'hffff_ffff; // 1 < 0xFFFFFFFF
        #10;
                   src0 = 32'h0000_0000; src1 = 32'h0000_0001; // 0 < 1（边界）
        #10;
                   src0 = 32'hffff_fffe; src1 = 32'hffff_ffff; // 最大值 - 1 < 最大值（边界）
        #10;
        op = 4'd4; src0 = 32'hffff_ffff; src1 = 32'h0f0f_0f0f; // 测试按位与 AND：全1 & 部分1
        #10;
                   src0 = 32'h1234_5678; src1 = 32'h0000_0000; // 任何数 & 0 = 0（边界）
        #10;
                   src0 = 32'haaaa_aaaa; src1 = 32'h5555_5555; // 互补位与（结果为 0）
        #10;
        op = 4'd5; src0 = 32'h0000_0000; src1 = 32'h1234_5678; // 测试按位或 OR：0 | 任何数
        #10;
                   src0 = 32'h0f0f_0f0f; src1 = 32'hf0f0_f0f0; // 互补位或（结果为全 1）
        #10;
                   src0 = 32'hffff_ffff; src1 = 32'hffff_ffff; // 全1 | 全1
        #10;
        op = 4'd6; src0 = 32'h0000_0000; src1 = 32'h0000_0000; // 测试按位或非 NOR：0 NOR 0（边界）
        #10;
                   src0 = 32'hffff_ffff; src1 = 32'hffff_ffff; // 全1 NOR 全1（边界）
        #10;
                   src0 = 32'h0f0f_0f0f; src1 = 32'hf0f0_f0f0; // 互补位或非
        #10;
        op = 4'd7; src0 = 32'h1234_5678; src1 = 32'h1234_5678; // 测试按位异或 XOR：相同数异或
        #10;
                   src0 = 32'h0f0f_0f0f; src1 = 32'hffff_ffff; // 与全1 异或（取反）
        #10;
                   src0 = 32'haaaa_aaaa; src1 = 32'h5555_5555; // 互补位异或（结果全1）
        #10;
        op = 4'd8; src0 = 32'h1234_5678; src1 = 32'h0000_0000; // 测试逻辑左移 SLL：左移 0 位（边界）
        #10;
                   src0 = 32'h0000_0001; src1 = 32'h0000_001f; // 左移 31 位（边界）
        #10;
                   src0 = 32'h0000_0001; src1 = 32'h0000_0020; // 左移 32 位（只看低 5 位，等同于左移 0 位）
        #10;
                   src0 = 32'h8000_0000; src1 = 32'h0000_0001; // 最高位左移（溢出）
        #10;
        op = 4'd9; src0 = 32'h1234_5678; src1 = 32'h0000_0000; // 测试逻辑右移 SRL：右移 0 位（边界）
        #10;
                   src0 = 32'h8000_0000; src1 = 32'h0000_001f; // 右移 31 位（边界）
        #10;
                   src0 = 32'hffff_ffff; src1 = 32'h0000_0004; // 负数逻辑右移（高位补 0）
        #10;
                   src0 = 32'h0000_0001; src1 = 32'h0000_0001; // 最低位右移（结果为 0）
        #10;
        op = 4'd10; src0 = 32'h1234_5678; src1 = 32'h0000_0004; // 测试算术右移 SRA：正数算术右移
        #10;
                    src0 = 32'shffff_ffff; src1 = 32'h0000_0004; // 负数算术右移（高位补 1）
        #10;
                    src0 = 32'sh8000_0000; src1 = 32'h0000_001f; // 最小负数右移 31 位（边界）
        #10;
                    src0 = 32'sh7fff_ffff; src1 = 32'h0000_001f; // 最大正数右移 31 位（边界）
        #10;
        op = 4'd11; src0 = 32'h1234_5678; src1 = 32'h8765_4321; // 测试传递 SRC1
        #10;
                    src0 = 32'hffff_ffff; src1 = 32'h0000_0000; // 传递 0（边界）
        #10;
                    src0 = 32'h0000_0000; src1 = 32'hffff_ffff; // 传递全 1（边界）
        #10;
    end

    ALU_1_1 alu(
        .src0(src0),
        .src1(src1),
        .op(op),
        .res(res)
    );
    
endmodule